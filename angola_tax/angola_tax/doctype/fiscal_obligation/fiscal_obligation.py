import math
import frappe
from frappe.utils import flt
from frappe.model.document import Document
from frappe.utils import (
    add_months,
    date_diff,
    get_last_day,
    getdate,
    nowdate,
)


class FiscalObligation(Document):

    def _validate_links(self):
        # Frappe checks child links before calling validate(). Rebind any
        # replaced GL Entry before that framework check runs.
        self.resolve_movement_gl_entries()
        super()._validate_links()

    def validate(self):
        self.validate_fiscal_period()
        self.resolve_movement_gl_entries()
        self.set_fiscal_year()
        self.set_statutory_due_dates()
        self.set_process_schedule_dates()
        self.set_submission_due_date()
        self.set_filing_due_date()
        self.process_movement_reviews()
        self.calculate_from_movements()
        self.validate_amounts()
        self.validate_submission()
        self.validate_filing()
        self.validate_assessment()
        self.calculate_variances()
        self.validate_variance_reason()
        self.calculate_outstanding_amount()
        self.calculate_accounting_reconciliation()
        self.calculate_submission_status()
        self.calculate_filing_status()
        self.calculate_deadline_status()
        self.calculate_compliance_status()
        self.validate_closure()

    def resolve_movement_gl_entries(self):
        """Rebind GL rows replaced by ERPNext, without changing tax meaning."""
        for row in self.movements or []:
            if not row.gl_entry:
                continue

            expected = {
                "company": self.company,
                "voucher_type": row.voucher_type,
                "voucher_no": row.voucher_no,
                "account": row.account,
            }
            stored = frappe.db.get_value(
                "GL Entry", row.gl_entry,
                ["company", "voucher_type", "voucher_no", "account",
                 "debit", "credit", "is_cancelled"],
                as_dict=True,
            )
            if stored:
                if (
                    stored.is_cancelled
                    or any(stored.get(key) != value for key, value in expected.items())
                    or abs(flt(stored.debit) - flt(row.debit)) >= 0.01
                    or abs(flt(stored.credit) - flt(row.credit)) >= 0.01
                ):
                    frappe.throw(
                        f"Row #{row.idx}: GL Entry {row.gl_entry} does not "
                        "match its Fiscal Obligation movement."
                    )
                continue

            matches = frappe.get_all(
                "GL Entry",
                filters={**expected, "is_cancelled": 0},
                fields=["name", "debit", "credit"],
                limit_page_length=0,
            )
            matches = [
                entry for entry in matches
                if abs(flt(entry.debit) - flt(row.debit)) < 0.01
                and abs(flt(entry.credit) - flt(row.credit)) < 0.01
            ]
            if len(matches) != 1:
                frappe.throw(
                    f"Row #{row.idx}: cannot uniquely match the GL Entry "
                    f"for {row.voucher_type} {row.voucher_no}. Review the "
                    "accounting movement before submitting."
                )

            current = matches[0].name
            if frappe.db.exists(
                "Fiscal Obligation Movement",
                {"gl_entry": current, "name": ["!=", row.name]},
            ):
                frappe.throw(
                    f"Row #{row.idx}: GL Entry {current} is already "
                    "linked to another Fiscal Obligation movement."
                )
            row.gl_entry = current

    def validate_fiscal_period(self):
        if (
            self.fiscal_period_from
            and self.fiscal_period_to
            and getdate(self.fiscal_period_from) > getdate(self.fiscal_period_to)
        ):
            frappe.throw(
                "Fiscal Period From cannot be later than Fiscal Period To."
            )

    def set_fiscal_year(self):
        if self.fiscal_period_to:
            self.fiscal_year = str(getdate(self.fiscal_period_to).year)
        elif self.fiscal_period_from:
            self.fiscal_year = str(getdate(self.fiscal_period_from).year)


    def set_statutory_due_dates(self):

        # A notification is an authority claim. Its payment date
        # comes from subsequent liquidation, not the operational
        # period-end deadline configuration.
        if self.obligation_origin == "Tax Notification":
            return

        rule = self.get_deadline_rule("Payment")

        if not rule:
            return

        # PERIODIC_STATUTORY_DEADLINE_V1
        #
        # The statutory tax clock is anchored to the
        # fiscal period generated by the accounting event.
        # Internal workflow/trigger dates must never move
        # the legal payment deadline.
        if not self.fiscal_period_to:
            return

        base_date = getdate(
            self.fiscal_period_to
        )

        due_month = add_months(
            base_date,
            rule.due_month_offset or 0,
        )

        if rule.use_end_of_month:
            due_date = get_last_day(due_month)

        elif rule.due_day:
            last_day = get_last_day(due_month).day
            due_day = min(rule.due_day, last_day)
            due_date = due_month.replace(day=due_day)

        else:
            return

        if not self.original_payment_due_date:
            self.original_payment_due_date = due_date

        if not self.current_payment_due_date:
            self.current_payment_due_date = due_date

    def set_process_schedule_dates(self):
        """
        Materialize company-defined internal process dates
        from Tax Deadline Configuration.

        Internal process dates are management controls only.
        They never alter the statutory legal deadline.
        """

        fields = (
            "determination_target_date",
            "determination_critical_date",
            "liquidation_target_date",
            "liquidation_critical_date",
            "payment_target_date",
            "payment_critical_date",
        )

        for fieldname in fields:
            self.set(fieldname, None)

        if (
            not self.company
            or not self.tax_type
            or not self.fiscal_period_to
        ):
            return

        period_end = getdate(
            self.fiscal_period_to
        )

        configurations = frappe.get_all(
            "Tax Deadline Configuration",
            filters={
                "company": self.company,
                "tax_type": self.tax_type,
                "active": 1,
                "docstatus": 1,
                "effective_from": ["<=", period_end],
            },
            fields=[
                "name",
                "effective_from",
                "effective_to",
            ],
            order_by="effective_from desc",
        )

        matching = []

        for config in configurations:
            if (
                config.effective_to
                and getdate(
                    config.effective_to
                ) < period_end
            ):
                continue

            matching.append(config)

        if len(matching) > 1:
            frappe.throw(
                "More than one active Tax Deadline "
                "Configuration applies to "
                f"{self.company} / {self.tax_type} "
                f"for period ending {period_end}."
            )

        if not matching:
            return

        config = frappe.get_doc(
            "Tax Deadline Configuration",
            matching[0].name,
        )

        for row in config.process_schedule or []:

            stage = row.process_stage

            target_date = (
                self._calculate_process_rule_date(
                    period_end,
                    row.target_month_offset,
                    row.target_day,
                    row.target_use_end_of_month,
                )
            )

            if row.critical_rule == "Legal Deadline":
                critical_date = (
                    self.original_payment_due_date
                )

            else:
                critical_date = (
                    self._calculate_process_rule_date(
                        period_end,
                        row.critical_month_offset,
                        row.critical_day,
                        row.critical_use_end_of_month,
                    )
                )

            if stage == "Determination":
                self.determination_target_date = (
                    target_date
                )
                self.determination_critical_date = (
                    critical_date
                )

            elif stage == "Liquidation":
                self.liquidation_target_date = (
                    target_date
                )
                self.liquidation_critical_date = (
                    critical_date
                )

            elif stage == "Payment":
                self.payment_target_date = (
                    target_date
                )
                self.payment_critical_date = (
                    critical_date
                )

    def _calculate_process_rule_date(
        self,
        period_end,
        month_offset,
        day,
        use_end_of_month,
    ):
        due_month = add_months(
            period_end,
            month_offset or 0,
        )

        if use_end_of_month:
            return get_last_day(
                due_month
            )

        if not day:
            return None

        last_day = get_last_day(
            due_month
        ).day

        return due_month.replace(
            day=min(
                int(day),
                last_day,
            )
        )


    def calculate_from_movements(self):
        if not self.movements:
            if self.obligation_origin == "Operational":
                self.amount_determined_raw = 0
                self.amount_determined = 0
                self.rounding_difference = 0
            return

        determined = 0
        # Payment is controlled centrally from confirmed
        # Tax Collection References / DC Pago.

        for row in self.movements:
            debit = row.debit or 0
            credit = row.credit or 0

            # Every GL movement stays in the audit trail. Only a
            # determined tax movement changes this exposure. A correction
            # must be reviewed as Determination to affect the balance.
            if row.movement_type == "Determination" and row.classification_status in (
                "Automatic", "Reviewed"
            ):
                determined += credit - debit
            elif self.is_posted_assessment_adjustment(row):
                # The separate adjustment label preserves its origin;
                # the posted GL entry also changes the current determination.
                amount = abs(credit - debit)
                determined += (
                    amount if row.movement_type == "Adjustment Increase"
                    else -amount
                )

        raw_determined = max(determined, 0)

        self.amount_determined_raw = raw_determined
        self.amount_determined = math.ceil(raw_determined)
        self.rounding_difference = (
            self.amount_determined - raw_determined
        )

        # Do not derive amount_paid from movements.
        # payment_control.py owns confirmed tax payments.

    def is_posted_assessment_adjustment(self, row):
        if (
            self.obligation_origin != "Operational"
            or row.voucher_type != "Journal Entry"
            or row.movement_type not in ("Adjustment Increase", "Adjustment Decrease")
            or row.classification_status not in ("Automatic", "Reviewed")
            or not row.gl_entry
        ):
            return False

        assessment = frappe.db.get_value(
            "Tax Assessment",
            {
                "fiscal_obligation": self.name,
                "adjustment_journal_entry": row.voucher_no,
                "docstatus": ["!=", 2],
            },
            ["assessment_variance", "company"],
            as_dict=True,
        )
        if not assessment or assessment.company != self.company:
            return False
        if (
            row.movement_type == "Adjustment Increase"
            and flt(assessment.assessment_variance) <= 0
        ) or (
            row.movement_type == "Adjustment Decrease"
            and flt(assessment.assessment_variance) >= 0
        ):
            return False
        return frappe.db.get_value("Journal Entry", row.voucher_no, "docstatus") == 1

    def validate_amounts(self):
        for fieldname in (
            "amount_determined",
            "amount_filed",
            "amount_assessed",
        ):
            value = self.get(fieldname) or 0

            if value < 0:
                frappe.throw(
                    f"{self.meta.get_label(fieldname)} cannot be negative."
                )

        if self.amount_filed and not self.amount_determined:
            frappe.throw(
                "Amount Determined is required before Amount Filed."
            )



    def calculate_variances(self):
        """
        Fiscal Obligation does not infer filing or assessment
        variances from lifecycle status.

        Assessment comparison belongs to Tax Assessment.
        Liquidation comparison belongs to Tax Settlement.

        Legacy variance fields are retained temporarily for
        compatibility but are not generated here.
        """
        self.filing_variance = 0
        self.assessment_variance = 0
        self.has_variance = 0


    def validate_variance_reason(self):
        if self.has_variance and not self.variance_reason:
            frappe.throw(
                "Variance Reason is required when an actual filing or assessment variance exists."
            )

    def calculate_outstanding_amount(self):
        """
        Calculate pre-liquidation exposure without deriving
        payment confirmation.

        Once a submitted Tax Settlement exists, payment_control.py
        owns the collectible amount, amount_paid and outstanding.
        """

        settlements = frappe.get_all(
            "Tax Settlement",
            filters={
                "fiscal_obligation": self.name,
                "docstatus": 1,
                "status": ["!=", "Cancelled"],
            },
            fields=["liquidated_amount"],
        )

        if settlements:
            liquidated_total = sum(
                flt(row.liquidated_amount)
                for row in settlements
            )

            self.effective_obligation_amount = (
                liquidated_total
            )

            self.outstanding_amount = max(
                liquidated_total
                - flt(self.amount_paid),
                0,
            )
            return

        # Before formal liquidation, the Fiscal Obligation
        # carries the determined/exposure amount.
        #
        # Authority assessments update the obligation through
        # Tax Assessment lifecycle logic. A submitted Settlement,
        # handled above, becomes the collectible basis.
        if self.obligation_origin == "Operational" and not flt(self.amount_assessed):
            # Recalculate when reviewed GL movements change determination;
            # zero must not fall back to a stale earlier amount.
            base_amount = flt(self.amount_determined)
        else:
            # Authority assessment exposure is maintained by Assessment.
            base_amount = (
                self.effective_obligation_amount
                or self.amount_assessed
                or self.amount_determined
                or 0
            )

        self.effective_obligation_amount = base_amount

        self.outstanding_amount = max(
            flt(base_amount) - flt(self.amount_paid),
            0,
        )

    def calculate_filing_status(self):
        self.is_filing_overdue = 0
        self.days_filing_overdue = 0

        if self.filing_date:
            self.filing_status = "Filed"
            return

        if not self.filing_due_date:
            self.filing_status = "No Deadline"
            return

        today = getdate(nowdate())
        due_date = getdate(self.filing_due_date)

        days_remaining = date_diff(due_date, today)

        if days_remaining < 0:
            self.is_filing_overdue = 1
            self.days_filing_overdue = abs(days_remaining)
            self.filing_status = "Overdue"

        elif days_remaining == 0:
            self.filing_status = "Due Today"

        elif days_remaining <= 5:
            self.filing_status = "Due Soon"

        else:
            self.filing_status = "Not Due"

    def calculate_deadline_status(self):
        self.is_overdue = 0
        self.days_overdue = 0

        # Fiscal Obligation keeps the obligation-level
        # compliance deadline only.
        #
        # RUPE-specific payment deadlines belong to
        # Tax Collection Reference.
        due_date = (
            self.current_payment_due_date
            or self.original_payment_due_date
        )

        self.effective_payment_due_date = due_date

        if (self.outstanding_amount or 0) <= 0:
            self.deadline_status = "Paid"
            return

        if not due_date:
            self.deadline_status = "No Deadline"
            return

        today = getdate(nowdate())
        due_date = getdate(due_date)

        days_remaining = date_diff(due_date, today)

        if days_remaining < 0:
            self.is_overdue = 1
            self.days_overdue = abs(days_remaining)
            self.deadline_status = "Overdue"

        elif days_remaining == 0:
            self.deadline_status = "Due Today"

        elif days_remaining <= 5:
            self.deadline_status = "Due Soon"

        else:
            self.deadline_status = "On Time"

    def calculate_compliance_status(self):
        self.compliance_alert = 0
        self.compliance_message = ""

        if self.is_submission_overdue:
            self.compliance_status = "Overdue"
            self.compliance_alert = 1
            self.compliance_message = (
                f"Fiscal obligation submission overdue by "
                f"{self.days_submission_overdue} day(s)."
            )
            return

        if self.status in ("Closed", "Cancelled"):
            self.compliance_status = "Closed"
            return

        if self.is_filing_overdue or self.is_overdue:
            self.compliance_status = "Overdue"
            self.compliance_alert = 1

            issues = []

            if self.is_filing_overdue:
                issues.append(
                    f"Filing overdue by {self.days_filing_overdue} day(s)"
                )

            if self.is_overdue:
                issues.append(
                    f"Payment overdue by {self.days_overdue} day(s)"
                )

            self.compliance_message = "; ".join(issues)
            return

        if (
            self.filing_status == "Due Today"
            or self.deadline_status == "Due Today"
        ):
            self.compliance_status = "Action Required"
            self.compliance_alert = 1
            self.compliance_message = (
                "Tax obligation requires action today."
            )
            return

        if (
            self.filing_status == "Due Soon"
            or self.deadline_status == "Due Soon"
        ):
            self.compliance_status = "Due Soon"
            self.compliance_alert = 1
            self.compliance_message = (
                "Tax obligation is approaching its deadline."
            )
            return

        if self.correction_required:
            self.compliance_status = "Action Required"
            self.compliance_alert = 1
            self.compliance_message = "Correction is required."
            return

        if self.status == "Paid" and self.original_payment_due_date:
            if not self.fully_paid_on:
                self.compliance_status = "Under Review"
                self.compliance_alert = 1
                self.compliance_message = (
                    "Confirmed payment date is missing; payment timeliness "
                    "cannot be verified."
                )
                return
            if self.paid_late:
                self.compliance_status = "Paid Late"
                self.compliance_message = (
                    f"Paid {self.days_paid_late} day(s) after the "
                    f"original due date {self.original_payment_due_date}."
                )
                return

        if self.status in ("Under Review", "Approved"):
            self.compliance_status = "Under Review"
            return

        self.compliance_status = "Compliant"

    def set_submission_due_date(self):
        rule = self.get_deadline_rule("Submission")

        if not rule:
            return

        period_end = getdate(self.fiscal_period_to)

        due_month = add_months(
            period_end,
            rule.due_month_offset or 0,
        )

        if rule.use_end_of_month:
            self.submission_due_date = get_last_day(due_month)

        elif rule.due_day:
            last_day = get_last_day(due_month).day
            due_day = min(rule.due_day, last_day)
            self.submission_due_date = due_month.replace(day=due_day)


    def calculate_submission_status(self):
        self.is_submission_overdue = 0
        self.days_submission_overdue = 0

        if self.submission_date:
            self.submission_status = "Submitted"
            return

        if not self.submission_due_date:
            self.submission_status = "No Deadline"
            return

        today = getdate(nowdate())
        due_date = getdate(self.submission_due_date)

        days_remaining = date_diff(due_date, today)

        if days_remaining < 0:
            self.is_submission_overdue = 1
            self.days_submission_overdue = abs(days_remaining)
            self.submission_status = "Overdue"

        elif days_remaining == 0:
            self.submission_status = "Due Today"

        elif days_remaining <= 3:
            self.submission_status = "Due Soon"

        else:
            self.submission_status = "Not Due"


    def get_deadline_rule(self, deadline_type):
        """
        Resolve the statutory legal deadline.

        Submission and Filing are legacy workflow concepts
        and no longer form part of the statutory deadline
        engine.

        The only statutory deadline resolved here is Payment.
        Internal Determination / Liquidation / Payment targets
        belong to the company Process Schedule.
        """

        if deadline_type != "Payment":
            return None

        if (
            not self.company
            or not self.fiscal_period_to
            or not self.tax_type
        ):
            return None

        period_end = getdate(
            self.fiscal_period_to
        )

        configurations = frappe.get_all(
            "Tax Deadline Configuration",
            filters={
                "company": self.company,
                "tax_type": self.tax_type,
                "active": 1,
                "docstatus": 1,
                "effective_from": ["<=", period_end],
            },
            fields=[
                "name",
                "effective_from",
                "effective_to",
            ],
            order_by="effective_from desc",
        )

        matching = []

        for config in configurations:
            if (
                config.effective_to
                and getdate(config.effective_to) < period_end
            ):
                continue

            matching.append(config)

        if len(matching) > 1:
            frappe.throw(
                "More than one active Tax Deadline "
                "Configuration applies to "
                f"{self.company} / {self.tax_type} "
                f"for period ending {period_end}."
            )

        if not matching:
            return None

        config = frappe.get_doc(
            "Tax Deadline Configuration",
            matching[0].name,
        )

        return frappe._dict(
            {
                "periodicity":
                    config.legal_periodicity,
                "due_month_offset":
                    config.legal_due_month_offset,
                "due_day":
                    config.legal_due_day,
                "use_end_of_month":
                    config.legal_use_end_of_month,
            }
        )

    def before_cancel(self):
        if (
            self.obligation_origin == "Tax Notification"
            or self.source_tax_notification
        ):
            frappe.throw(
                "A Fiscal Obligation created from a Tax Notification "
                "cannot be cancelled independently. "
                "The Tax Notification is the authoritative source."
            )

        matched_payments = [
            row for row in (self.movements or [])
            if row.movement_type == "Payment"
        ]

        if matched_payments:
            frappe.throw(
                "Cannot cancel this Fiscal Obligation while payment movements are matched. "
                "Unmatch or reverse the payment allocation first."
            )

        if self.accounting_reconciled:
            frappe.throw(
                "Cannot cancel a reconciled Fiscal Obligation. "
                "Reverse the reconciliation first."
            )

    def before_update_after_submit(self):
        self.resolve_movement_gl_entries()
        submitted_amount = flt(frappe.db.get_value(
            "Fiscal Obligation", self.name, "amount_determined"
        ))
        self.process_movement_reviews()
        self.calculate_from_movements()

        if (
            self.obligation_origin == "Operational"
            and abs(flt(self.amount_determined) - submitted_amount) > 0.001
        ):
            # Submitted operational determinations stay locked against
            # ordinary late bookings. Only a linked, posted Assessment JE
            # may change this balance after the original submission.
            stored_rows = frappe.get_all(
                "Fiscal Obligation Movement",
                filters={"parent": self.name},
                fields=["name", "voucher_type", "voucher_no", "account",
                        "movement_type", "classification_status",
                        "debit", "credit", "gl_entry"],
            )

            def determination_value(rows):
                return sum(
                    flt(row.credit) - flt(row.debit)
                    for row in rows
                    if row.movement_type == "Determination"
                    and row.classification_status in ("Automatic", "Reviewed")
                )

            original = determination_value(stored_rows)
            current = determination_value(self.movements or [])
            existing_adjustments_unchanged = all(
                any(
                    item.name == old.name
                    and item.voucher_type == old.voucher_type
                    and item.voucher_no == old.voucher_no
                    and item.account == old.account
                    and item.movement_type == old.movement_type
                    and flt(item.debit) == flt(old.debit)
                    and flt(item.credit) == flt(old.credit)
                    for item in self.movements or []
                )
                for old in stored_rows
                if old.movement_type in ("Adjustment Increase", "Adjustment Decrease")
                and self.is_posted_assessment_adjustment(old)
            )
            if abs(current - original) > 0.001 or not existing_adjustments_unchanged:
                frappe.throw(
                    "A submitted Fiscal Obligation cannot change its "
                    "Determined Amount through a late GL movement. "
                    "Review the posting and use the formal correction process."
                )

        self.validate_submission()
        self.validate_filing()
        self.validate_assessment()
        self.calculate_variances()
        self.validate_variance_reason()
        self.calculate_outstanding_amount()
        self.calculate_accounting_reconciliation()
        self.calculate_submission_status()
        self.calculate_filing_status()
        self.calculate_deadline_status()
        self.calculate_compliance_status()
        self.validate_closure()

    def set_filing_due_date(self):
        rule = self.get_deadline_rule("Filing")

        if not rule:
            return

        period_end = getdate(self.fiscal_period_to)

        due_month = add_months(
            period_end,
            rule.due_month_offset or 0,
        )

        if rule.use_end_of_month:
            self.filing_due_date = get_last_day(due_month)

        elif rule.due_day:
            last_day = get_last_day(due_month).day
            due_day = min(rule.due_day, last_day)
            self.filing_due_date = due_month.replace(day=due_day)


    def before_submit(self):
        if self.obligation_origin == "Tax Notification":
            if not self.source_tax_notification:
                frappe.throw("Source Tax Notification is required.")

            notification = frappe.get_doc(
                "Tax Notification", self.source_tax_notification
            )
            if notification.fiscal_obligation != self.name:
                frappe.throw(
                    "Tax Notification and Fiscal Obligation must be linked to each other."
                )
            return

        if self.obligation_origin in (
            "Direct Assessment",
            "Assessment Successor",
        ):
            if not self.source_tax_assessment:
                frappe.throw(
                    "Source Tax Assessment is required for a Direct Assessment obligation."
                )

            assessment = frappe.get_doc(
                "Tax Assessment",
                self.source_tax_assessment,
            )

            return

        if not self.movements:
            frappe.throw(
                "Fiscal Obligation cannot be submitted without accounting movements."
            )

        if (self.amount_determined or 0) <= 0:
            frappe.throw(
                "Amount Determined must be greater than zero before submission."
            )

        unclassified = [
            row for row in self.movements
            if row.classification_status == "Unclassified"
            or row.movement_type == "Unclassified"
        ]

        if unclassified:
            frappe.throw(
                f"{len(unclassified)} accounting movement(s) remain unclassified. "
                "Review them before submitting the Fiscal Obligation."
            )

        self.reviewed_by = frappe.session.user
        self.reviewed_on = frappe.utils.now()

        # A reviewed operational obligation is determined, but is
        # not yet collectible. Formal collectibility begins with
        # Tax Settlement / liquidation.
        self.status = "Awaiting Liquidation"


    def validate_submission(self):
        submission_started = bool(
            self.submission_date
            or self.submission_reference
        )

        if not submission_started:
            return

        if not self.submission_date:
            frappe.throw(
                "Submission Date is required when recording a statutory submission."
            )

        if not self.submission_reference:
            frappe.throw(
                "Submission Reference is required when recording a statutory submission."
            )


    def validate_filing(self):
        filing_started = bool(
            self.amount_filed
            or self.filing_date
            or self.declaration_reference
        )

        if not filing_started:
            return

        if self.docstatus != 1:
            frappe.throw(
                "Fiscal Obligation must be submitted before filing information can be recorded."
            )

        if not self.filing_date:
            frappe.throw(
                "Filing Date is required when recording a tax filing."
            )

        if not self.declaration_reference:
            frappe.throw(
                "Declaration Reference is required when recording a tax filing."
            )


    def validate_assessment(self):
        """
        Validate assessment metadata held on the Fiscal Obligation.

        An authority assessment may exist independently of a
        taxpayer filing. Filing is therefore not a prerequisite.

        Nota de Lancamento / RUPE collectibility is not validated
        here. Formal liquidation belongs to Tax Settlement and
        payment references belong to Tax Collection Reference.
        """

        assessment_started = bool(
            self.nota_lancamento_reference
            or self.nota_lancamento_date
            or self.amount_assessed
            or self.latest_tax_assessment
        )

        if not assessment_started:
            return

        # Assessment information normally belongs to a submitted
        # Fiscal Obligation.
        #
        # Exception: a Direct AGT Assessment creates the Fiscal
        # Obligation itself, so assessment exposure may be present
        # while that new obligation is still Draft.
        if (
            self.docstatus == 0
            and (
                self.amount_assessed
                or self.latest_tax_assessment
            )
            and self.obligation_origin not in (
                "Direct Assessment", "Tax Notification"
            )
        ):
            frappe.throw(
                "Fiscal Obligation must be submitted before "
                "assessment information can be recorded."
            )

    def validate_closure(self):
        if self.status not in ("Reconciled", "Closed"):
            return

        unclassified = [
            row for row in (self.movements or [])
            if row.classification_status == "Unclassified"
            or row.movement_type == "Unclassified"
        ]

        if unclassified:
            frappe.throw(
                "Cannot reconcile or close while accounting movements remain unclassified."
            )

        if (self.outstanding_amount or 0) != 0:
            frappe.throw(
                "Cannot reconcile or close while an outstanding amount remains."
            )

        if self.has_variance and self.correction_required:
            frappe.throw(
                "Cannot reconcile or close while a tax variance still requires correction."
            )

        if not self.accounting_reconciled:
            frappe.throw(
                "Accounting reconciliation must be completed before closing the obligation."
            )


    def calculate_accounting_reconciliation(self):
        unclassified = [
            row for row in (self.movements or [])
            if row.classification_status == "Unclassified"
            or row.movement_type == "Unclassified"
        ]

        if unclassified:
            self.accounting_reconciled = 0
            self.reconciliation_date = None
            return

        if (self.outstanding_amount or 0) != 0:
            self.accounting_reconciled = 0
            self.reconciliation_date = None
            return

        if not self.movements:
            self.accounting_reconciled = 0
            self.reconciliation_date = None
            return

        self.accounting_reconciled = 1

        if not self.reconciliation_date:
            self.reconciliation_date = nowdate()

    def process_movement_reviews(self):
        for row in self.movements or []:
            # Keep an unchanged automatic classification. If the user
            # changes its movement type, it becomes a human review.
            if row.classification_status == "Automatic":
                previous = (
                    frappe.db.get_value(
                        "Fiscal Obligation Movement",
                        row.name,
                        ["movement_type", "classification_status"],
                        as_dict=True,
                    )
                    if row.name and not row.is_new()
                    else None
                )
                if not previous or (
                    previous.classification_status == "Automatic"
                    and previous.movement_type == row.movement_type
                ):
                    continue

            # Still unresolved.
            if not row.movement_type or row.movement_type == "Unclassified":
                row.classification_status = "Unclassified"
                row.reviewed_by = None
                row.reviewed_on = None
                continue

            # A human has assigned a fiscal meaning.
            row.classification_status = "Reviewed"

            if not row.reviewed_by:
                row.reviewed_by = frappe.session.user

            if not row.reviewed_on:
                row.reviewed_on = frappe.utils.now()
